"""Pack assets/ into game-assets/: smaller files, same frames.

- HD frames are re-encoded from lossless pixels (tools/hd_lossless.py) as
  AVIF with full colour (4:4:4), which keeps costume edges sharp.
- The 2780 x 7141 pixel sheet is split into one sheet per character, so no
  sheet goes over the 16.7 million pixel limit some phones have.
- manifest.json keeps every clip, fps, anchor and release frame; only the
  file paths and pixel rectangles change.

    python3 tools/pack_assets.py [--quality 70]
"""
import argparse, io, json, os, shutil, subprocess, sys
from multiprocessing import Pool
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "game-assets")
LOSSLESS = os.path.join(ROOT, "build", "lossless")


def encode(job):
    source, dest, quality = job
    im = Image.open(os.path.join(LOSSLESS, source + ".png")).convert("RGBA")
    im.save(dest, "AVIF", quality=quality, subsampling="4:4:4", speed=6)
    return os.path.getsize(dest)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quality", type=int, default=70)
    args = ap.parse_args()

    if not os.path.exists(os.path.join(LOSSLESS, "frames.json")):
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "hd_lossless.py"), LOSSLESS], check=True)

    man = json.load(open(os.path.join(SRC, "manifest.json")))
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    os.makedirs(os.path.join(OUT, "pixel"))

    jobs, done = [], {}
    sheet = Image.open(os.path.join(SRC, man["pixel"]["sheet"]))
    cell = man["pixel"]["cell"]
    for char, cv in man["characters"].items():
        rects = {}   # big-sheet rectangle -> slot in this character's sheet
        for clip, d in cv["clips"].items():
            for f in d["frames"]:
                hd = f["hd"].rsplit(".", 1)[0] + ".avif"
                if hd not in done:
                    done[hd] = True
                    os.makedirs(os.path.dirname(os.path.join(OUT, hd)), exist_ok=True)
                    jobs.append((f["source"], os.path.join(OUT, hd), args.quality))
                f["hd"] = hd
                key = (f["pixel"]["x"], f["pixel"]["y"])
                rects.setdefault(key, len(rects))
        cols = 10
        rows = -(-len(rects) // cols)
        out = Image.new(sheet.mode, (cols * cell["w"], rows * cell["h"]))
        if sheet.mode == "P":
            out.putpalette(sheet.getpalette())
            out.info["transparency"] = sheet.info.get("transparency", 0)
        for (x, y), i in rects.items():
            r, c = divmod(i, cols)
            out.paste(sheet.crop((x, y, x + cell["w"], y + cell["h"])), (c * cell["w"], r * cell["h"]))
        path = f"pixel/{char}.png"
        out.save(os.path.join(OUT, path), optimize=True, transparency=out.info.get("transparency", 0))
        cv["pixel_sheet"] = path
        for d in cv["clips"].values():
            for f in d["frames"]:
                r, c = divmod(rects[(f["pixel"]["x"], f["pixel"]["y"])], cols)
                f["pixel"] = dict(x=c * cell["w"], y=r * cell["h"], w=cell["w"], h=cell["h"])

    with Pool(4) as pool:
        total = sum(pool.map(encode, jobs))

    man["hd"]["format"] = f"avif 4:4:4 q{args.quality} with alpha, re-encoded from lossless frames by tools/pack_assets.py"
    man["pixel"].pop("sheet", None)
    man["pixel"]["sheets"] = "one per character: characters.<name>.pixel_sheet"
    man["note"] = "Generated by tools/pack_assets.py from assets/manifest.json. Do not hand-edit; regenerate."
    json.dump(man, open(os.path.join(OUT, "manifest.json"), "w"), indent=1)
    px = sum(os.path.getsize(os.path.join(OUT, "pixel", p)) for p in os.listdir(os.path.join(OUT, "pixel")))
    print(f"{len(jobs)} HD frames: {total / 1e6:.2f} MB; pixel sheets: {px / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
